"""Turn RioModPack/assets/Online.png into OnlineTexture.h.

    python RioModPack/MakeOnlineTexture.py

The main menu's seven button labels are 156x21 GX C4 textures (4-bit palette
indices, 8x8 tiles) with a 16-entry IA8 palette, all in the ZZZZ.dat container
the menu loads under tag 6 (entry 1740: textures t49 and t52-t57). The Online
label was drawn from those same glyphs, so it fits a 16-entry intensity+alpha
palette exactly and encodes with no loss.

Output layout, the shape "Online Menu.c" expects:
  s_onlineTexture   bytes 0 .. 1919   C4 pixels (160x24 after tile padding, 2 px/byte)
                    bytes 1920..1951  TLUT, 16 x IA8 (alpha byte, intensity byte)
"""
import os
import struct
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "assets", "Online.png")
DST = os.path.join(HERE, "OnlineTexture.h")

W, H = 156, 21
LABEL_DATA = 1920
LABEL_TLUT = 32


def ia(p):
    r, g, b, a = p
    return ((r * 77 + g * 151 + b * 28) >> 8, a)


def encode_label():
    im = Image.open(SRC).convert("RGBA")
    if im.size != (W, H):
        sys.exit("Online.png must be %dx%d, got %dx%d" % (W, H, im.size[0], im.size[1]))
    px = im.load()
    counts = {}
    for y in range(H):
        for x in range(W):
            k = ia(px[x, y])
            counts[k] = counts.get(k, 0) + 1
    pal = sorted(counts, key=lambda k: -counts[k])
    if len(pal) > 16:
        base = pal[:16]

        def near(k):
            return min(range(16), key=lambda j: (base[j][0] - k[0]) ** 2 + 2 * (base[j][1] - k[1]) ** 2)
        idx = {k: near(k) for k in pal}
        pal = base
        print("warning: %d intensity/alpha pairs, quantised to 16" % len(counts))
    else:
        idx = {k: i for i, k in enumerate(pal)}
    tlut = b"".join(struct.pack(">BB", a, i) for (i, a) in pal)
    tlut += bytes(LABEL_TLUT - len(tlut))

    def at(x, y):
        return idx[ia(px[x, y])] if x < W and y < H else 0
    out = bytearray()
    for by in range(0, H, 8):
        for bx in range(0, W, 8):
            for yy in range(8):
                for xx in range(0, 8, 2):
                    out.append((at(bx + xx, by + yy) << 4) | at(bx + xx + 1, by + yy))
    assert len(out) == LABEL_DATA, len(out)
    return bytes(out) + tlut, len(pal)


def dump(lines, name, blob, per_line):
    lines.append("static const unsigned char %s[%d]" % (name, len(blob)))
    lines.append("    __attribute__((aligned(32))) = {")
    for i in range(0, len(blob), per_line):
        lines.append("    " + ", ".join("0x%02X" % b for b in blob[i:i + per_line]) + ",")
    lines.append("};")


def main():
    label, nlabel = encode_label()
    lines = ["/* GENERATED by RioModPack/MakeOnlineTexture.py from assets/Online.png -- do not",
             " * edit. 32-byte aligned because the GPU reads it in place. */",
             "#define ONLINE_TEX_DATA_SIZE %d" % LABEL_DATA,
             "#define ONLINE_TEX_TLUT_SIZE %d" % LABEL_TLUT,
             "/* 156x21 GX C4 pixel tiles followed by a 16-entry IA8 TLUT. */"]
    dump(lines, "s_onlineTexture", label, 16)
    with open(DST, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", DST, "(%d colours)" % nlabel)


if __name__ == "__main__":
    main()
